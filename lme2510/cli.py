def _warm(cold):
    """Run the P5b on a cold device and return the warm one. One line on stderr.

    The owner's decision (2026-11-18): a cold `3344:1120` is warmed by the driver when it
    needs the stick, the way the IT drivers do, instead of being a per-run instruction for
    the user. `lme2510/warm.py` builds the 75 frames from the two images; this function
    owns the device handle and the wait for the re-enumeration.
    """
    code, blob = warm.load_images()
    frames = warm.build(code, blob)
    device = transport.Device(cold)
    device.open()
    try:
        def find_warm():
            found = [d for d in transport.devices()
                     if d.idProduct == warm.WARM_PID]
            return found[0] if found else None

        warm_device = warm.bring_up(device, frames, look_for_warm=find_warm)
    finally:
        # the interface is usually gone after the reset; a close that fails for any other reason
        # says so instead of disappearing (see close_quietly)
        close_quietly(device, "warm")
    print("cold 1120 -> warm 2480 (P5b, %d/%d)" % (len(frames), len(frames)),
          file=sys.stderr)
    return warm_device


#: A just-reset device can be enumerated before it is openable. Measured on the real stick, 2026-11-20:
#: inside the recovery ladder, two seconds after `8a 00`, the re-open failed with `[Errno 13] Access denied`
#: while the device was present, warm, on the same bus address — and a fresh process opened it immediately.
#: So the knock is retried; the *recovery* is still judged by what the device answers (`verify_alive`).
OPEN_TRIES = 10
OPEN_PAUSE = 0.25

#: Seconds to wait for the device to reappear on the bus after it left.
RECONNECT_WAIT = 10.0


def open_handle(usb_device, tries=OPEN_TRIES, pause=OPEN_PAUSE):
    """``transport.Device(usb_device).open()``, retried while the OS refuses the fresh node.

    Returns the open handle or raises the last error (pyusb's `USBError` is an `OSError`). Only the open
    is retried — a handle that opens is then asked to answer a register read, so a retry can never turn a
    dead device into a passing recovery.
    """
    last = None
    for attempt in range(tries):
        try:
            return transport.Device(usb_device).open()
        except (OSError, RuntimeError, ValueError) as error:
            last = error
            if attempt + 1 < tries:
                time.sleep(pause)
    raise last


def _reconnect(args):
    """Reopen the stick after it left the bus; returns ``(device, core)`` or None.

    The stick resets and re-enumerates under load (LEAP 2026-11-18: three identities in
    six seconds), and it sometimes comes back **cold** `3344:1120`, which needs the P5b
    before the warm init can run. So this waits for it to reappear, warms it if it came
    back cold, then re-inits, re-tunes and restarts the stream — the same path a fresh
    start takes, so nothing new can go wrong in it.
    """
    deadline = time.monotonic() + RECONNECT_WAIT
    usb_device = None
    device = None                  # the failure paths below must never touch an unbound name
    while time.monotonic() < deadline:
        usb_device = transport.find()
        if usb_device is not None:
            break
        time.sleep(0.25)
    if usb_device is None:
        print("stream    no LME2510 on the bus after %.0f s" % RECONNECT_WAIT, file=sys.stderr)
        return None
    try:
        if usb_device.idProduct == warm.COLD_PID:
            usb_device = _warm(usb_device)
    except warm.BringUpError as failure:
        print("stream    %s" % failure, file=sys.stderr)
        return None
    try:
        device = open_handle(usb_device)
        # the node this handle is on, so the pair (before -> after) is in the log (IT9308 rule 7)
        print("stream    opened %s" % device.identity_line(), file=sys.stderr, flush=True)
        # A halted endpoint outlives the reopen: the firmware's RAM survives a bus reset (trap 17), so
        # the fresh handle clears the halts before anything is sent on it. Per endpoint and cheap;
        # deliberately not `libusb_reset_device` (see transport.Device.clear_halt).
        cleared, failed = device.clear_halt()
        if failed:
            print("stream    halt not cleared on %s" % ", ".join(
                "0x%02x (%s)" % (address, error) for address, error in failed),
                file=sys.stderr, flush=True)
        elif cleared:
            print("stream    cleared halt on %d endpoint(s)" % len(cleared),
                  file=sys.stderr, flush=True)
        # the same construction `_open` uses, byte for byte: a reconnect that built the
        # driver differently would be a second code path to get wrong
        adapter = driver.DeviceTransport(
            device, getattr(args, "frame_delay_ms", 0.0) / 1000.0)
        core = driver.Driver(adapter, wait=lambda: time.sleep(0.001))
        _result, failure = _init(core)
        if failure:
            print("stream    re-init failed: %s" % failure, file=sys.stderr)
            close_quietly(device, "stream")
            return None
        locked, _trace = tune_and_lock(core, args.freq)
        # The rebuild is verified on the new handle, never by "did packets arrive": a quiet channel and
        # a wedged stick both carry zero packets (IT9308, 2026-11-20).
        answer = verify_alive(core)
        if answer is None:
            print("stream    the fresh handle answered nothing on 0x%04x: the rebuild failed"
                  % ALIVE_REGISTER, file=sys.stderr, flush=True)
            close_quietly(device, "stream")
            return None
        print("stream    reconnected, %d kHz %s, 0x%04x answered 0x%02x"
              % (args.freq, "LOCKED" if locked else "no lock", ALIVE_REGISTER, answer),
              file=sys.stderr, flush=True)
        core.start_stream(pids=stream_filter_pids(args))
    except (ValueError, OSError, RuntimeError) as error:  # noqa: BLE001
        print("stream    reconnect failed: %s" % error, file=sys.stderr)
        close_quietly(device, "stream")
        return None
    return device, core


def _open(args):
    usb_device = transport.find()
    if usb_device is None:
        raise SystemExit("no LME2510 device on the bus (3344:1120 or 3344:2480)")
    if usb_device.idProduct == warm.COLD_PID:
        if getattr(args, "no_warm", False):
            raise SystemExit("3344:1120 is cold and --no-warm was given: plug it in "
                             "after a warm host, or drop --no-warm")
        try:
            usb_device = _warm(usb_device)
        except warm.BringUpError as failure:
            raise SystemExit(str(failure))
    device = transport.Device(usb_device)
    try:
        device.open()
    except Exception as error:  # noqa: BLE001
        # a TV front end/tuner.py's _friendly() turns "cannot claim" into "the stick is
        # busy: another program is using it" -- so say that instead of a traceback
        message = str(error)
        if "busy" in message.lower() or "access" in message.lower():
            raise SystemExit("cannot claim the device (busy): %s" % message)
        raise
    if getattr(args, "frame_delay_ms", None):
        adapter = driver.DeviceTransport(device, args.frame_delay_ms / 1000.0)
    else:
        adapter = driver.DeviceTransport(device)
    core = driver.Driver(adapter, wait=lambda: time.sleep(0.001))
    return device, adapter, core


def cmd_list(_args):
    try:
        found = transport.devices()
    except Exception as missing:  # noqa: BLE001 - one line, non-zero exit, never a traceback
        print(str(missing).replace("\n", " "))
        return 1
    if not found:
        print("no LME2510 device on the bus (3344:1120 or 3344:2480)")
        return 1
    for device in found:
        if device.idProduct == 0x2480:
            note = ""
        else:
            # a host app's device list skips a line whose USB id is followed by
            # "not this driver" within 80 characters -- say it in its words, so the
            # player does not offer a stick that cannot tune yet.
            note = "  will warm on use"
        product = "2480 (warm)" if device.idProduct == 0x2480 else "1120 (cold)"
        print("%04x:%04x  %s%s  bus %s addr %s"
              % (device.idVendor, device.idProduct, product, note,
                 device.bus, device.address))
    return 0


