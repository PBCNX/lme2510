class TsSink:
    """The play sink: file, stdout or UDP, optionally with the null packets dropped.

    `--drop-null` matters for the a TV front end: it reads the stream through a pipe, so
    every null packet is bytes it has to write while the USB reads wait behind it.
    Dropping them keeps the 188-byte alignment and leaves a valid stream.
    """

    NULL_PID = 0x1FFF

    def __init__(self, write, drop_null=False):
        self._write = write
        self.drop_null = drop_null
        self.packets = 0
        self.nulls = 0
        self.cc = 0                    # continuity discontinuities seen so far
        self.quality = quality.Quality()   # the studio's shared window
        self.desync = 0                # packets that did not start with 0x47
        self._buffer = b""
        self._cc_tail = b""            # the no-drop path carries its own tail
        self._last_cc = {}             # PID -> the last counter that had payload

    def __call__(self, data):
        if not self.drop_null:
            self.packets += len(data) // 188
            self._count_cc(data)
            self.quality.mark()
            self._write(data)
            return
        # Walk packet by packet, resyncing on 0x47, and copy the packets we keep.
        #
        # Two bugs have lived here, both found by the host app on hardware:
        #  1. `self._buffer = self._buffer[188:]` per packet made one call O(n^2); with
        #     1 MiB reads the reader fell behind and the stick dropped packets
        #     (2026-11-17). Fixed by walking an index.
        #  2. the walk then assumed 188-byte alignment *forever*. The raw stream slips
        #     occasionally (stray bytes, ~8 times in 90 s, measured 2026-11-18), and
        #     after the first slip the walk read PIDs at wrong offsets and cut ~16 % of
        #     the stream in 188-byte windows. Now every header is checked against 0x47
        #     and a slip is repaired by searching for the next packet start.
        buf = self._buffer + data
        end = len(buf)
        out = bytearray()
        index = 0
        while True:
            start = _packet_start(buf, index, end)
            if start < 0:
                break
            if start != index:
                self.desync += 1       # stray bytes between packets: skipped, reported
            pid = ((buf[start + 1] & 0x1F) << 8) | buf[start + 2]
            self._see(start, buf[start + 3], pid, tei=(buf[start + 1] & 0x80) != 0)
            if pid == self.NULL_PID:
                self.nulls += 1
            else:
                out += buf[start:start + 188]
                self.packets += 1
            index = start + 188
        self._buffer = buf[index:]
        self.quality.mark()
        if out:
            self._write(bytes(out))

    def _see(self, index, control, pid, tei=False):
        """One packet's continuity, counted in place: no second pass over the chunk.

        Also feeds the shared quality window: a packet is evaluable when it is not a
        null and carries payload, and it is unclean when TEI is set or the continuity
        counter breaks (a repeat is not a break).
        """
        if pid == self.NULL_PID:
            return                     # nulls carry no meaningful counter
        adaptation = (control >> 4) & 0x03
        if adaptation != 1 and adaptation != 3:
            return                     # no payload: the counter does not advance
        counter = control & 0x0F
        previous = self._last_cc.get(pid)
        broken = False
        if previous is not None:
            expected = (previous + 1) & 0x0F
            if counter != expected and counter != previous:
                self.cc += 1           # a duplicate (same counter) is not a jump
                broken = True
        self._last_cc[pid] = counter
        self.quality.observe(tei, broken)

    def _count_cc(self, data):
        """Count continuity over whole packets in `data` (the no-drop-null path).

        The tail of a packet split across two chunks **is carried**, the same as the
        drop-null path: a chunk of 51,200 B is 272 packets plus 64 bytes, so walking
        from offset 0 every call misaligns everything after the first chunk (it
        reported 142,160 jumps on a run that lost nothing — host app, 2026-11-18).

        A duplicate (same counter as the last packet of that PID) is not a jump, a PID
        with no payload does not advance its counter, and nulls are skipped because
        their continuity counter means nothing to us.
        """
        buf = self._cc_tail + data
        end = len(buf)
        index = 0
        while True:
            start = _packet_start(buf, index, end)
            if start < 0:
                break
            if start != index:
                self.desync += 1
            pid = ((buf[start + 1] & 0x1F) << 8) | buf[start + 2]
            self._see(start, buf[start + 3], pid, tei=(buf[start + 1] & 0x80) != 0)
            index = start + 188
        self._cc_tail = buf[index:]


def status_line(packets, locked, strength="n/a", cc=None, quality="n/a"):
    """The line `a TV front end/tuner.py` parses, verbatim in shape.

    Its STATUS regex is ``ts packets (\\d+)\\s+lock (\\w+)\\s+strength (\\S+)
    \\s+quality (\\S+)``, and it reads ``locked = m[2] == "True"`` — so the
    word must be `True` or `False`, not LOCK. Lock is the vendor's first test (0x3025
    bit 0).

    ``strength`` is the reading taken **once at tune** (see `lme2510.rssi`), on our
    relative 0–100 map — not dBm, and never re-read while streaming. It is `n/a` when
    the channel did not lock or the device did not answer.

    ``quality`` is the studio's shared definition over a sliding window (see
    `lme2510.quality`): 100 × clean packets / total, where a packet is unclean if TEI
    is set or its continuity counter breaks. It is `n/a` until the first full window,
    and it is a property of what we received, not a C/N measurement.
    """
    line = "ts packets %d lock %s strength %s quality %s" % (
        packets, "True" if locked else "False", strength, quality)
    if cc is not None:
        line += " cc %d" % cc
    return line


def scan_line(freq_khz, locked, strength="n/a"):
    """The line `a TV front end/tuner.py`'s scanner parses: ``NNN kHz LOCK strength S``."""
    return "%d kHz %s strength %s" % (freq_khz, "LOCK" if locked else "no lock",
                                       strength)


#: Consecutive device losses the supervisor rebuilds through before it gives up. The
#: budget is per loss *in a row*, not per run: a stick that reconnects every few minutes
#: must not run out of patience (the GMA app supervises for the life of the session).
RECONNECT_LIMIT = 5
#: Software recovery: how many times a stalled pump gets a rebuild inside one run. A *per-run* cap
#: rather than a lifetime budget: a bad evening dies once instead of a good session dying after a year
#: (IT9175's rule, 2026-11-20).
RECOVER_TRIES = 3
#: Retained for callers that used the first name; same value.
RECOVER_ATTEMPTS = RECOVER_TRIES
#: How long a scan's byte check gives a locked channel to produce TS (default).
DEFAULT_VERIFY_SECONDS = 1.5
#: Seconds to hold the handle closed so the device sees the release (IT9175: close, wait, reopen).
RECOVER_PAUSE = 2.0
#: The vendor's own MCU reset, `LYDEV_ResetMCU` §7): the closest thing this chip
#: has to a firmware reboot. Sent write-only on a wedge — see `fire_and_forget`.
CHIP_RESET = bytes([0x8A, 0x00])
#: How long the packet counter may stand still before the pump is called stalled.
STALL_SECONDS = 3.0

#: A TS packet is 188 bytes and starts with this. Used to repair a slipped stream.
SYNC_BYTE = 0x47
PACKET = 188


def _packet_start(buf, index, end):
    """The offset of the next whole packet at or after ``index``; -1 when there is none.

    A packet needs 188 bytes: fewer than that remain means the caller must keep the tail
    for the next chunk, not emit a short packet (found by a test that split at 188·k + 100).

    ``buf[index] == 0x47`` is taken as a packet start: that is the definition of sync, and
    it keeps the packet that a slip happens *behind* (the stray bytes follow it). Only when
    the byte is not a sync byte do we search, and the search demands a second sync byte one
    packet later, so a lone 0x47 inside a payload cannot restart us on a wrong boundary.
    """
    if index + PACKET > end:
        return -1
    if buf[index] == SYNC_BYTE:
        return index
    scan = index + 1
    while scan + PACKET <= end:
        if buf[scan] == SYNC_BYTE:
            following = scan + PACKET
            if following + PACKET > end or buf[following] == SYNC_BYTE:
                return scan
        scan += 1
    return -1


class StallWatch:
    """Notices a TS pump that stopped, using only the packet counter.

    This exists because the honest way to poll a running stream is to touch nothing:
    the moment the status loop read a register, the pump stopped (measured: 233 KiB/s
    with the read against 987.5 without, Windows 2026-11-17). A counter that stops
    advancing is the signal we can get for free, and it is the one the player needs —
    without it, ffmpeg waits on an empty pipe forever.
    """

    def __init__(self, seconds=STALL_SECONDS):
        self.seconds = seconds
        self.last = None
        self.moved_at = None
        self.hit = False

    def reset(self):
        """Forget the last sample: used when a reconnect makes a gap legitimate."""
        self.last = None
        self.moved_at = None
        self.hit = False

    def observe(self, packets, now=None):
        """Return True exactly once, when the counter has not moved for `seconds`."""
        now = time.monotonic() if now is None else now
        if self.last is None or packets != self.last:
            self.last = packets
            self.moved_at = now
            return False
        if self.moved_at is None:
            self.moved_at = now
            return False
        if not self.hit and now - self.moved_at >= self.seconds:
            self.hit = True
            return True
        return False


def _init(core):
    """Run the warm init, turning a refusal into one line instead of a traceback.

    `calibration.run` raises RuntimeError("VCO calibration failed: ...") when the sweep
    reads nothing usable -- which is what a *cold* stick does, because the warm init
    cannot run on one. The a TV front end shows whatever we print on stderr, so this is one
    line and a non-zero exit, not a stack.
    """
    try:
        return core.init(), None
    except RuntimeError as error:
        return None, str(error)


class TimedSink:
    """Times every sink call: the host app asked for this to see whether the pump
    waits behind the output side ."""

    def __init__(self, inner):
        self.inner = inner
        self.calls = 0
        self.total = 0.0
        self.worst = 0.0

    def __call__(self, data):
        started = time.perf_counter()
        try:
            self.inner(data)
        finally:
            elapsed = time.perf_counter() - started
            self.calls += 1
            self.total += elapsed
            self.worst = max(self.worst, elapsed)

    def summary(self):
        return ("sink %d calls, %.1f ms total, worst %.1f ms"
                % (self.calls, self.total * 1000.0, self.worst * 1000.0))


def timed_source(source):
    """Wraps a `source(size, timeout_ms)` and reports the worst gap between returns."""
    record = {"calls": 0, "worst": 0.0, "last": time.perf_counter()}

    def wrapped(size, timeout_ms):
        before = time.perf_counter()
        data = source(size, timeout_ms)
        now = time.perf_counter()
        record["calls"] += 1
        record["worst"] = max(record["worst"], now - record["last"])
        record["last"] = now
        wrapped.last_duration = now - before
        return data

    wrapped.record = record
    wrapped.last_duration = 0.0
    return wrapped


def cmd_play(args):
    from lme2510 import reader

    device, _adapter, core = _open(args)
    # The pair, before anything happens (IT9308's rule 7): a reset's shape is per host — the same bare
    # reset kept the address on Windows and re-enumerated on macOS, on two different bridges (2026-11-20)
    # — so a run that may recover has to log the node it started on, or the later sentence cannot be
    # checked. Guarded because the tests hand this command a fake device without one.
    if callable(getattr(device, "identity_line", None)):
        print("device    %s" % device.identity_line(), file=sys.stderr, flush=True)
    handle = open(args.out, "wb") if args.out and args.out != "-" else None
    sender = None
    if args.udp:
        from lme2510 import udp
        host, port = udp.parse_target(args.udp)
        sender = udp.UdpSender(host, port)
        write = sender.send
        where = "udp://%s:%d" % (host, port)
    elif handle is not None:
        write = handle.write
        where = args.out
    else:
        write = sys.stdout.buffer.write
        where = "stdout"
    sink = TsSink(write, drop_null=args.drop_null)
    timed_sink = TimedSink(sink) if args.stats else None
    active_sink = timed_sink or sink
    until = threading.Event()
    status_stop = threading.Event()
    status_thread = None
    try:
        _result, failure = _init(core)
        if failure:
            print("init      failed: %s" % failure, file=sys.stderr)
            return 2
        try:
            locked, _trace = tune_and_lock(core, args.freq)
        except ValueError as error:
            print("tune      refused: %s" % error, file=sys.stderr)
            return 2
        # everything except the TS goes to stderr: with --out - stdout IS the stream
        print("tune      %d kHz, %s" % (args.freq, "LOCKED" if locked else "no lock"),
              file=sys.stderr)
        # The strength snapshot, taken ONCE here and never while streaming: a read
        # during the stream costs most of it (measured 2026-11-16). Every status line
        # repeats this number.
        #
        # Read it whether or not the scan said "locked": it is a read *before* the stream
        # starts, so it is free, and S is a level — not a lock verdict. Gating it on the
        # scan printed `strength n/a` on a channel that then carried 524 KiB/s (Linux
        # hardware, 2026-11-18), which reads as "no signal" and was wrong.
        level = rssi.read(core)
        strength = rssi.token(level)
        core.start_stream(pids=stream_filter_pids(args))
        if args.status_interval and args.status_interval > 0:
            stall_seconds = getattr(args, "stall_seconds", None) or STALL_SECONDS

            def status_loop():
                watch = StallWatch(stall_seconds)
                while not status_stop.wait(args.status_interval):
                    # A status thread that dies silently is worse than no status thread:
                    # the stall detector lives in here too, so a formatting error would
                    # take the watchdog with it and the run would look healthy while the
                    # pump was dead. Measured 2026-11-18: one 20-minute run on the Mac
                    # logged nothing after the tune line and nothing said why.
                    try:
                        status_tick(watch)
                    except Exception as trouble:  # noqa: BLE001
                        print("status    loop failed (%s); stall detection is off"
                              % trouble, file=sys.stderr, flush=True)
                        return

            def status_tick(watch):
                # NOTHING here may touch the device: a register read while the
                # stream runs stops the TS pump (measured 2026-11-16 and again on
                # Windows 2026-11-17: 233 KiB/s with the read, 987.5 without).
                # The lock word is the scan's verdict, frozen at tune, and the
                # stall detector works on the packet counter alone.
                #
                # Except for one correction, and it is the studio's own rule — the
                # stream is the final verdict. A scan CAN refuse a channel that
                # plays: measured on the LEAP 2026-11-18, 497143 answered
                # `0x50c5 = 0x00` (no lock) and then carried 531.7 KiB/s. So when
                # bytes arrive on a channel the scan rejected, say so once and
                # believe the bytes.
                if not locked and sink.packets > 0 and not stall.get("adopted"):
                    stall["adopted"] = True
                    print("lock      False by the scan, but the stream arrived: "
                          "treating it as locked (a scan can refuse a channel "
                          "that plays)", file=sys.stderr, flush=True)
                shown = True if stall.get("adopted") else locked
                print(status_line(sink.packets, shown, strength, sink.cc,
                                  sink.quality.token()),
                      file=sys.stderr, flush=True)
                if stall.get("paused"):
                    # A rebuild's gap is legitimate. The flag is cleared *here*, not by the rebuild
                    # itself: a fast rebuild can finish between two ticks, and then the watch would
                    # keep `hit` set and never fire again — the ladder ran once and reported a healthy
                    # "0 B" run (found by tests/test_play_wedge.py, 2026-11-20).
                    watch.reset()
                    stall["paused"] = False
                elif watch.observe(sink.packets):
                    stall["hit"] = True
                    print("stream stalled: no TS for %.0f s" % watch.seconds,
                          file=sys.stderr, flush=True)
                    # No replug advice here while recovery is on: this is state 3, the driver's own job
                    # (IT9175's contract, and IT9308's and ours). The cable advice belongs to an absent
                    # device (state 4) or to a user who asked for no automatic recovery at all —
                    # printing it while the rebuild below then succeeds is the exact escalation the
                    # family corrected three times on 2026-11-20.
                    if getattr(args, "no_recover", False):
                        hint = no_ts_hint(locked, sink.packets)
                        if hint:
                            print(hint, file=sys.stderr, flush=True)
                    until.set()


            status_thread = threading.Thread(target=status_loop, daemon=True)
            status_thread.start()
        started = time.monotonic()
        stall = {"hit": False}
        source = reader.transport_source(device)
        timed = timed_source(source) if args.stats else None
        stream = reader.StreamReader(timed or source, readers=args.readers,
                                     sink=active_sink, presence=device_on_bus)
        def run_once():
            if args.seconds is None:
                # live, as the a TV front end runs it: until SIGINT/SIGTERM
                previous = {}
                for signame in ("SIGINT", "SIGTERM"):
                    signum = getattr(signal, signame, None)
                    if signum is None:
                        continue
                    previous[signame] = signal.signal(signum, lambda *_: until.set())
                try:
                    return stream.run(None, until=until)
                finally:
                    for signame, handler in previous.items():
                        signal.signal(getattr(signal, signame), handler)
            return stream.run(args.seconds)

        if getattr(args, "reset_after", 0.0) and args.reset_after > 0:
            def reset_later():
                # the device answers 0a 00 and then resets; anything it does after that is
                # the point of the exercise, so the errors here are expected and ignored
                time.sleep(args.reset_after)
                print("stream    hardware: sending 0a 00 (USB reset) after %.1f s"
                      % args.reset_after, file=sys.stderr, flush=True)
                try:
                    core.exchange(bytes([0x0A, 0x00]))
                except Exception:  # noqa: BLE001
                    pass
            threading.Thread(target=reset_later, daemon=True).start()

        reconnects = 0
        recoveries = 0

        def software_recover(reason, reset=True):
            """Close, wait, re-open, re-init, re-tune — and a chip reset first when asked.

            Both ways a pump dies go through here — a wedge (silence, device present) and an endpoint
            fault on a device that is still on the bus. That is deliberate: two ladders for one state is
            how a driver ends up with a recovery that works in one branch and not the other. Returns the
            new ``(device, core)`` or None when nothing came back.

            `reset=False` is IT9175's ordering, adopted 2026-11-20 after the hardware showed what the other
            order costs: on an idle carrier (485143, 99.7 % nulls) the ladder ran three times and sent
            **three chip resets to a device that was answering perfectly**. A fresh handle is the cheaper
            primitive, so the first attempt is a handle and only the second reaches for the chip.
            """
            nonlocal device, core
            stall["paused"] = True
            print("stream    %s; software recover (try %d): %s"
                  % (reason, recoveries,
                     "chip reset, then a fresh handle" if reset
                     else "a fresh handle (the device answers, so replace the handle first)"),
                  file=sys.stderr, flush=True)
            # The vendor's own MCU reset (`8a 00`, LYDEV_ResetMCU) is the closest thing this chip has to
            # IT9175's force_boot: a reset of the on-chip firmware rather than of the USB side.
            # **Fire and forget** (IT9308, 2026-11-20): on a wedged command endpoint the read is the
            # failure, so the frame goes out, nothing is read, and the fresh handle below is the proof.
            if not reset:
                close_quietly(device, "stream")
            try:
                if reset:
                    wrote_only = fire_and_forget(core, CHIP_RESET)
                    print("stream    chip reset (8a 00) sent%s"
                          % (" without reading (a read on a wedged endpoint is what stalls)"
                             if wrote_only else " (this transport has no write-only path)"),
                          file=sys.stderr, flush=True)
            except Exception as error:  # noqa: BLE001
                print("stream    chip reset (8a 00) could not be sent (%s); rebuilding anyway"
                      % error, file=sys.stderr, flush=True)
            if reset:
                close_quietly(device, "stream")
            time.sleep(RECOVER_PAUSE)
            recovered = _reconnect(args)
            if recovered is not None:
                device, core = recovered
            return recovered

        # A failed rebuild that left the device on the bus should try the rebuild again, not read a handle
        # that was just closed: this flag skips the dead pump for exactly one pass.
        retry_without_stream = [False]
        while True:
            try:
                if retry_without_stream[0]:
                    retry_without_stream[0] = False
                else:
                    total = run_once()
                # A channel that never locked is not a wedged device: there is nothing to recover, and
                # resetting a healthy chip three times for it is what this line did on 487143 and on a
                # dark 599143 (measured 2026-11-20, Windows and macOS). `stall["adopted"]` is the
                # believe-the-stream exception: bytes without a lock verdict mean the channel *is* there.
                if stall["hit"] and not (locked or stall.get("adopted")):
                    print("stream    no signal: the scan never locked this channel and no stream arrived "
                          "- nothing to recover, and the device was not touched", file=sys.stderr,
                          flush=True)
                    break
                # The pump stopped while the device stayed on the bus. A USB reset does not clear
                # this firmware's state (SMSRIO, 2026-11-20), but **closing the handle and opening a
                # fresh one does** in most cases (IT9175: five of five) — so try the software step
                # before telling the user to reach for the cable.
                if not should_recover(stall["hit"], recoveries,
                                      getattr(args, "no_recover", False)):
                    if stall["hit"]:
                        if getattr(args, "no_recover", False):
                            # The user asked for no automatic recovery, so nothing was tried and the
                            # "after N rebuild(s)" wording would be a lie.
                            print("stream    the pump stopped and --no-recover is set: nothing was "
                                  "tried (this is state 3, which the driver would otherwise own)",
                                  file=sys.stderr, flush=True)
                        else:
                            print(state3_line(recoveries), file=sys.stderr, flush=True)
                    break
                recoveries += 1
                recovered = software_recover("pump stalled", reset=recoveries > 1)
                if recovered is None:
                    # Measured on the real stick (2026-11-20): the re-open can fail while the device is
                    # present, warm, on the same address. That is state 3 — the driver's job — and saying
                    # "no LME2510 on the bus" would be a lie that sends the user to the cable. Only an
                    # absent device is state 4.
                    if device_on_bus():
                        print("stream    the rebuild could not bring it back, but the device is still on "
                              "the bus: retrying (state 3, %d/%d)"
                              % (recoveries, RECOVER_TRIES), file=sys.stderr, flush=True)
                        retry_without_stream[0] = True
                        continue
                    print(state4_line(), file=sys.stderr, flush=True)
                    break
                source = reader.transport_source(device)
                if args.stats:
                    source = timed_source(source)
                stream = reader.StreamReader(source, readers=args.readers,
                                             sink=active_sink, presence=device_on_bus)
                # The rebuilt session must not inherit the stop event the stall set: in live mode
                # `run(None, until=until)` would return on its first look and every further rebuild
                # would "finish" instantly, reporting exit 3 on a device that was answering again.
                until.clear()
                stall["hit"] = False
                continue
            except reader.DeviceGone as gone:
                # IT9308's rule (2026-11-20), adopted here: **a detach is silence and absence**. A read
                # error alone is also what a halted endpoint looks like, and reopening a device that
                # never left the bus hides exactly the state trap 17 is about. So ask the bus first: if
                # the stick is still enumerated, this is a wedge and `software_recover` owns it.
                if device_on_bus():
                    # Either the device never left (a halted endpoint: state 3) or it left and came back
                    # before we noticed. Both are the software ladder's job, but the message must not
                    # claim which one it was — on macOS a pull can surface only after a replug.
                    print("detach    the stream's handle failed (%s) and a device is on the bus: "
                          "rebuilding the session" % gone, file=sys.stderr, flush=True)
                    if not should_recover(True, recoveries, getattr(args, "no_recover", False)):
                        print("stream    the endpoint failed again and the software recover is spent "
                              "(state 3): %s" % gone, file=sys.stderr, flush=True)
                        return 4
                    recoveries += 1
                    recovered = software_recover("endpoint failed", reset=recoveries > 1)
                    if recovered is None:
                        if device_on_bus():
                            print("stream    the endpoint failed and the rebuild could not open it, but "
                                  "the device is still on the bus: retrying (state 3, %d/%d)"
                                  % (recoveries, RECOVER_TRIES), file=sys.stderr, flush=True)
                            retry_without_stream[0] = True
                            continue
                        print(state4_line(), file=sys.stderr, flush=True)
                        return 4
                    source = reader.transport_source(device)
                    if args.stats:
                        source = timed_source(source)
                    stream = reader.StreamReader(source, readers=args.readers,
                                                 sink=active_sink, presence=device_on_bus)
                    until.clear()
                    stall["hit"] = False
                    continue
                # The GMA app's pattern, which is the model for this loop: it never revives a dead
                # handle, it supervises - on detach it tears the TV path down, on attach it rebuilds
                # the path and restores the channel from cache. That is why a replug looks seamless
                # there, and it is why the count below is *consecutive* losses rather than a
                # lifetime budget: a stick that reconnects every few minutes must not run out.
                if getattr(args, "no_reconnect", False):
                    print("detach    device left the bus: %s (--no-reconnect, stopping)" % gone,
                          file=sys.stderr)
                    return 4
                reconnects += 1
                if reconnects > RECONNECT_LIMIT:
                    print("detach    device left the bus %d times in a row, giving up: %s"
                          % (reconnects - 1, gone), file=sys.stderr)
                    return 4
                print("detach    device gone (%s); tearing the TV path down" % gone,
                      file=sys.stderr, flush=True)
                stall["paused"] = True
                close_quietly(device, "detach")
                recovered = _reconnect(args)
                if recovered is None:
                    # The device left and did not come back: state 4, the one case a hand can fix.
                    print(state4_line(), file=sys.stderr, flush=True)
                    return 4
                device, core = recovered
                print("attach    rebuilding the TV path: %d kHz%s"
                      % (args.freq, "" if not reconnects else " (after %d loss(es))" % reconnects),
                      file=sys.stderr, flush=True)
                source = reader.transport_source(device)
                if args.stats:
                    source = timed_source(source)
                stream = reader.StreamReader(source, readers=args.readers,
                                             sink=active_sink, presence=device_on_bus)
                # same reason as the wedge branch: a detach that followed a stall leaves the stop
                # event set, and the rebuilt run would end on its first look
                until.clear()
        elapsed = max(time.monotonic() - started, 1e-9)
        extra = ", %d null dropped" % sink.nulls if sink.nulls else ""
        print("stream    %d B in %.1f s (%.1f KiB/s) -> %s%s"
              % (total, elapsed, total / 1024.0 / elapsed, where, extra),
              file=sys.stderr)
        if timed_sink is not None:
            print("stats     " + timed_sink.summary(), file=sys.stderr)
            print("stats     reads %d, worst gap between reads %.1f ms"
                  % (timed.record["calls"], timed.record["worst"] * 1000.0),
                  file=sys.stderr)
        if stall["hit"]:
            return 4                     # the pump stopped; the player must not hang on it
        return 0 if total else 3
    finally:
        status_stop.set()
        if status_thread is not None:
            status_thread.join(timeout=1.0)
        if sender is not None:
            close_quietly(sender, "udp")
        if handle is not None:
            close_quietly(handle, "out")
        close_quietly(device, "stream")


def lock_trace_line(freq, trace):
    """One line from a lock scan's trace: the `0x50c5` story in the vendor application's columns.

    `first nonzero`, `zeros before it` and `max over the rest` are the three numbers that
    separate "the demod settled late" from "it locked at the threshold" — the same columns
    the host app logs, so the two tables can be compared row by row.
    """
    values = [value for register, value, _step in trace if register == 0x50C5]
    if values:
        zeros = 0
        while zeros < len(values) and not values[zeros]:
            zeros += 1
        if zeros == len(values):
            story = "0x50c5 0 (x%d)" % len(values)
        else:
            first = values[zeros]
            rest = [value for value in values[zeros + 1:] if value]
            story = "0x50c5 %d zero%s -> 0x%02x, max 0x%02x" % (
                zeros, "" if zeros == 1 else "s", first,
                max(rest) if rest else first)
    else:
        story = "0x50c5 not reached"
    seen = []
    for register, value, _step in trace:
        if register != 0x50C5:
            seen.append("0x%04x=0x%02x" % (register, value))
    return "lock trace %d kHz: %s%s" % (freq, story,
                                        (" " + " ".join(seen)) if seen else "")


def _channel_has_data(device, seconds=DEFAULT_VERIFY_SECONDS, chunk=None):
    """Start nothing: the caller has already started the pump. True when a TS chunk arrives in `seconds`.

    A lock is necessary, not sufficient (measured 2026-11-15 at 485143, and again 2026-11-20 on 509143 and
    485143: `scan LOCKED` with zero bytes). This is the scan's byte check, the same rule the zap ladder uses.
    """
    source = reader.transport_source(device)
    size = chunk or reader.CHUNK
    deadline = time.monotonic() + max(0.05, seconds)
    while time.monotonic() < deadline:
        try:
            data = source(size, 300)
        except Exception:  # noqa: BLE001 - a read error here means "no data", the caller reports it
            return False
        if data:
            return True
    return False


def cmd_scan(args):
    """Sweep channels and print the lines the player's scanner reads.

    One open and one init, then tune and scan each frequency. The format is
    `a TV front end/tuner.py`'s SCAN_LINE; a frequency the plan refuses is skipped.
    """
    device, _adapter, core = _open(args)
    try:
        _result, failure = _init(core)
        if failure:
            print("init      failed: %s" % failure, file=sys.stderr)
            return 2
        candidates = []
        for freq in range(args.start, args.stop + 1, args.step):
            try:
                locked, trace = tune_and_lock(core, freq)
            except ValueError:
                continue
            if getattr(args, "trace", False):
                print(lock_trace_line(freq, trace), file=sys.stderr, flush=True)
            # the level is a read before anything streams, so it costs nothing: report it
            # even when the scan refused, because S is a level and not a lock verdict
            level = rssi.read(core)
            print(scan_line(freq, locked, rssi.token(level)), flush=True)
            if locked:
                candidates.append(freq)

        if getattr(args, "verify", False):
            # A lock is necessary, not sufficient (measured 2026-11-20: 683143 passed the scan at strength 0,
            # with zero bytes behind it). The byte check is the verdict - the same rule the zap ladder uses.
            #
            # It runs as a SECOND pass, and each candidate gets a fresh init first. Measured the same evening:
            # a byte check that started the pump mid-sweep left the device streaming, and every channel after
            # it refused to lock (485, 491, 497, 503 - on 497 with signal at strength 22). The driver has no
            # stop-stream frame, so the tuner is reset the way the driver resets it: init again.
            for freq in candidates:
                _result, failure = _init(core)
                if failure:
                    print("verify    init failed before %d kHz: %s" % (freq, failure), file=sys.stderr)
                    break
                try:
                    locked, _trace = tune_and_lock(core, freq)
                except ValueError:
                    continue
                if not locked:
                    print("verify    %d kHz: no lock on the re-check (the first pass said locked)"
                          % freq, flush=True)
                    continue
                core.start_stream()
                has_data = _channel_has_data(device, getattr(args, "verify_seconds",
                                                            DEFAULT_VERIFY_SECONDS))
                verdict = ("station (locked + bytes)" if has_data else
                           "locked but no data - carrier or false lock, check it before trusting the row")
                print("verify    %d kHz: %s" % (freq, verdict), flush=True)
    finally:
        close_quietly(device, "scan")
    return 0


def align_ts(data):
    """Slice a capture to its first 188-byte packet boundary.

    The first read after `start_stream` lands wherever the device was in its packet, so a buffer can be
    up to 187 bytes out of phase — and then every parser reads garbage and reports "nothing found",
    which on 2026-11-20 turned a real EWBS descriptor into "no 0xFC descriptor in 154 MB". The sink
    resyncs for `--drop-null`; this is the same idea for parsing, and it returns the data unchanged when
    it is already aligned or when no run of four packets confirms a boundary.
    """
    limit = min(len(data), 188 * 4)
    for offset in range(limit):
        if offset + 188 * 3 >= len(data):
            break
        if all(data[offset + 188 * step] == 0x47 for step in range(4)):
            return data[offset:]
    return data


def close_quietly(device, where):
    """Close a handle and print the failure instead of swallowing it. Returns True when closed.

    IT9308's lesson (2026-11-20): a `None` device in a `finally` destroyed the diagnosis of the bug they
    were chasing — the traceback pointed at the cleanup, not the cause. So every close in this file goes
    through here: `None` is a no-op, a failure is one line on stderr with the caller's name on it, and no
    close ever raises out of a `finally`.
    """
    if device is None:
        return False
    try:
        closed = device.close()
    except Exception as error:  # noqa: BLE001
        print("%s    close failed: %s" % (where, error), file=sys.stderr, flush=True)
        return False
    if closed is False:
        print("%s    close reported a failure (see the transport log)" % where,
              file=sys.stderr, flush=True)
        return False
    return True


def device_on_bus():
    """True when an LME2510 is still enumerated — the half of IT9308's detach rule we can ask for.

    A read error is not a detach by itself: a halted endpoint and a vanished device both raise, and one
    of them is a wedge (state 3, the driver's job) while the other is a replug (state 4 for the user, a
    supervisor rebuild for us). The rule adopted from IT9308 on 2026-11-20 is *silence **and** absence*;
    this function answers the "absence" half. Split out and patched by the tests so a run on a hardware with
    a stick present cannot silently change what a fake-transport test is asserting.
    """
    try:
        return transport.find() is not None
    except Exception:  # noqa: BLE001
        return False          # cannot enumerate at all: treat it as gone, which is the old path


def fire_and_forget(core, frame):
    """Write a frame and never read its reply. Returns True when it went out write-only.

    On a wedged command endpoint **the read is the failure** (IT9308, 2026-11-20): the answer to a reset
    is sent by a device that is already resetting, so waiting for it costs the timeout and often the
    session. The reset is therefore a fire-and-forget write followed by a fresh handle — and the proof
    that the rebuild worked is a register answer on that new handle (`verify_alive`), not a reply here.

    A core without a write-only path (`send`) still gets the frame through `exchange`; the return value
    tells the caller which happened, so the log line cannot claim more than it knows.
    """
    send = getattr(core, "send", None)
    if callable(send):
        send(frame)
        return True
    core.exchange(frame)
    return False


#: A status register the tune already reads. Only the *presence* of an answer is used here — see
#: `verify_alive` — so its value carries no meaning of its own.
ALIVE_REGISTER = 0x0F76


def verify_alive(core, register=ALIVE_REGISTER):
    """The device's answer to one register read, or None when it answered nothing.

    IT9308's rule, adopted 2026-11-20: **verify a recovery on the new handle, never by "did packets
    arrive"**. A quiet channel and a wedged stick both produce zero packets, so a rebuild that only
    waits for bytes cannot tell success from failure — and would either give up on a good channel or
    declare victory on a dead one. A register read can tell: a live device answers `0x55` + payload, a
    wedged one answers nothing. The *value* is not the test; the tune's own meaning for `0x0f76` is not
    needed here, only that something came back.
    """
    try:
        value = core.read(register)
    except Exception:  # noqa: BLE001
        return None
    return value[0] if value else None


#: The PID the filter frame names when a user asks to *see* the nulls (`--keep-null`). The list is a
#: **suppression** list, so naming an unused PID leaves 0x1FFF in the stream. Measured 2026-11-20: 485143
#: locks and is **317 nulls out of 318 packets**, so the default filter (which drops 0x1FFF) makes an idle
#: carrier look dead — the "locked, no data" shape.
KEEP_NULL_PID = 0x1FFE


def stream_filter_pids(args):
    """The PIDs to suppress for this run: the nulls by default, an unused PID with `--keep-null`."""
    return (KEEP_NULL_PID,) if getattr(args, "keep_null", False) else (0x1FFF,)


#: A first tune right after the init can miss on a marginal channel, and a second tune locks. Measured on
#: 485143, 2026-11-20: three passes in one session per round - `tune1 FAILED (142 reads), tune2 LOCKED
#: (108), tune3 LOCKED (109)` and `tune1 FAILED (22), tune2 LOCKED (109), tune3 LOCKED (108)` - while the
#: strong control (479143) locked on tune1 in all three rounds. The tune itself already retries its VCO
#: calibration four times, so the retry belongs here: re-run the whole tune, not a longer poll.
TUNE_TRIES = 2


def tune_and_lock(core, freq, tries=TUNE_TRIES, on_tune=None):
    """Tune, scan, and tune **again** if the scan refused. Returns ``(locked, trace)``.

    One tune is ~30 writes and a calibration - cheaper than a false "no signal", which is what a single
    pass produced on this hardware for a channel that locks every time it is asked twice. The retry does not
    grade anything: it just gives the demod the second chance the vendor's own flow always had (its init
    ends on a default tune, so the first real tune is never the first tune in the session).

    `on_tune(word)` is called with each attempt's `0x76` byte, for the commands that print it.
    """
    locked, trace = False, []
    for attempt in range(max(1, tries)):
        word = core.tune(freq)
        if on_tune is not None:
            on_tune(word)
        locked, trace = core.scan()
        if locked:
            break
    return locked, trace


def should_recover(stalled, attempts, disabled):
    """Whether a stalled pump gets another rebuild inside this run.

    The family contract (IT9175, 2026-11-20): **states 1-3 are automatic, only state 4 reaches a
    human.** A wedge on a present device is state 3 — the driver's job — so this returns True until
    the per-run budget is spent, and the message about the cable is reserved for an absent device.
    """
    return bool(stalled) and not disabled and attempts < RECOVER_TRIES


def state3_line(attempts):
    """What was tried, for a wedge that did not clear. Never the replug advice — that is state 4."""
    return ("state 3   the wedge did not clear after %d rebuild(s): tried the chip reset (8a 00), "
            "a fresh handle, and a cold upload if it came back blank" % attempts)


def state4_line():
    """The one case a human can fix: the device is not on the bus at all."""
    return ("state 4   no LME2510 on the bus: unplug and replug the stick - that is the only "
            "guaranteed power cycle")


def no_ts_hint(locked, packets):
    """What to do when the stream is stuck — one line, or None when there is nothing to say.

    A USB reset is not a device reset on these sticks: the firmware's RAM survives it, so a disabled
    interface or a halted endpoint outlives a reset and only a power cycle clears it (SMSRIO measured
    the same on their chip, 2026-11-20; this line has carried the shape as "locked, no data" for days).
    A driver that reports only the stall leaves the user retrying a command that cannot work.

    But there is a cheaper explanation, measured 2026-11-20 on an idle carrier: **the driver drops the
    null packets**, and a mux that is 99.7 % nulls then looks dead while it is arriving perfectly. So the
    hint names `--keep-null` first — one command, no cable — and keeps the cable for what it is for.
    """
    if not locked:
        return None
    if packets == 0:
        return ("hint      the demod reports the lock and not one packet has arrived: if this mux is "
                "idle it may be almost all null packets (485143 measured 317 of 318), which the driver "
                "drops - try --keep-null. Otherwise unplug and replug the stick: a USB reset does not "
                "clear its firmware state")
    return ("hint      the stream stopped after %d packets: try --keep-null if this channel is idle, "
            "then try again, and if it repeats, unplug and replug the stick" % packets)


def ewbs_verdict(reading, descriptor_count, captions):
    """One line: the transmission-layer flag against the stream's own signals.

    EWBS has two independent carriers here — the TMCC B26 flag, which the demod decodes from the
    frame, and the `0xFC` descriptor in the PMT. Either can be present without the other, and a
    descriptor with the flag off is a test transmission rather than an alert (H3 §7.1), so the line
    reports all three facts and says which one carried the alert.
    """
    flag = "unknown" if reading is None else ("on" if reading["ewbs"] else "off")
    descriptor = "present" if descriptor_count else "absent"
    caption_state = "present" if captions else "absent"
    if reading is None:
        verdict = "no TMCC reading: the descriptor is the only evidence here"
    elif reading["ewbs"] and descriptor_count:
        verdict = "alert signalled on both carriers"
    elif reading["ewbs"]:
        verdict = "the transmission layer is the only signal"
    elif descriptor_count:
        verdict = "descriptor without the flag: a test transmission, not an alert"
    else:
        verdict = "no alert on either carrier"
    return "TMCC B26 %s, PMT 0xFC %s, caption %s - %s" % (
        flag, descriptor, caption_state, verdict)


def cmd_ewbs(args):
    from lme2510 import caption, ewbs, psi

    device, _adapter, core = _open(args)
    buffer = bytearray()
    reading = None
    try:
        _result, failure = _init(core)
        if failure:
            print("init      failed: %s" % failure, file=sys.stderr)
            return 2
        try:
            locked, _trace = tune_and_lock(core, args.freq)
        except ValueError as error:
            print("tune      refused: %s" % error, file=sys.stderr)
            return 2
        print("tune      %d kHz, %s" % (args.freq, "LOCKED" if locked else "no lock"))
        # TMCC first, and before start_stream: every command stops this device's TS pump, so the
        # flag has to be read while the demod is idle or the alert costs the stream.
        if locked:
            try:
                reading = tmcc.decode(tmcc.read_settled(core))
            except ValueError as error:
                print("tmcc      %s" % error, file=sys.stderr)
                reading = None
            else:
                if tmcc.valid(reading):
                    print("tmcc      %s" % tmcc.describe(reading))
                else:
                    # No layer claims segments, so this block is not a multiplex and its B26 bit
                    # cannot be reported as "off" - that would be a claim the reading cannot make.
                    print("tmcc      not decoded yet (the block claims no layer segments); the flag "
                          "is unknown, not off", file=sys.stderr)
                    reading = None
        else:
            print("tmcc      unknown (the demod reads TMCC only while locked)")
        core.start_stream()
        stream = reader.StreamReader(reader.transport_source(device), sink=buffer.extend)
        stream.run(args.seconds)
    finally:
        close_quietly(device, "ewbs")

    data = align_ts(bytes(buffer))
    found = 0
    for program, pmt_pid in psi.programs(data):
        for section in psi.iter_sections(data, pmt_pid):
            for descriptor in ewbs.descriptors(section):
                found += 1
                areas = " ".join("0x%03x" % code for code in descriptor["area_codes"])
                print("EWBS      PMT 0x%04x program 0x%04x: service 0x%04x, %s, "
                      "signal_level %d, %d area code(s)"
                      % (pmt_pid, program, descriptor["service_id"],
                         "start" if descriptor["start_end_flag"] else "end",
                         descriptor["signal_level"], len(descriptor["area_codes"])))
                if areas:
                    print("          area codes: %s" % areas)
            break
    if not found:
        print("EWBS      no 0xFC descriptor in %.1f MB" % (len(data) / 1e6))
    shown = 0
    for pid, body in caption.pes_bodies(data):
        _parameters, text = caption.statement(body)
        if text:
            shown += 1
            print("caption   PID 0x%04x: %r" % (pid, text))
        if shown >= 4:
            break
    if not shown:
        print("caption   none")
    print("ewbs      %s" % ewbs_verdict(reading, found, shown))
    return 0 if found or shown else 2


def cmd_doctor(_args):
    """Say which layer is wrong before anyone blames the driver.

    Checks, in order: the Python stack, pyusb, the libusb backend, the udev rule on
    Linux, and finally whether the device is on the bus. Each failure names the fix
    for that platform, so a first run on Windows or macOS says
    what to do instead of "no device".
    """
    import os
    import platform

    problems = []
    print("driver    lme2510 %s" % __version__)
    print("python    %s on %s" % (platform.python_version(), platform.platform()))

    # the driver loads pyusb through its own bootstrap (a vendored copy sits in
    # vendor/), so ask it rather than importing `usb` from the ambient path
    try:
        transport._pyusb()
        import usb
        vendored = any(os.sep + "vendor" in entry for entry in sys.path)
        print("pyusb     %s%s" % (getattr(usb, "__version__", "installed"),
                                  " (vendored)" if vendored else ""))
    except ImportError:
        print("pyusb     MISSING")
        problems.append("install pyusb: python -m pip install pyusb")

    try:
        found = transport.backend()
        if found is None:
            print("libusb    MISSING (no backend)")
            problems.append("install libusb-1.0 (Windows: a libusb build or Zadig "
                            "WinUSB binding; macOS: brew install libusb)")
        else:
            print("libusb    backend present")
    except Exception:  # noqa: BLE001
        print("libusb    MISSING (python module)")
        problems.append("install libusb-1.0")

    if platform.system() == "Linux":
        rule = "/etc/udev/rules.d/99-lme2510.rules"
        if os.path.exists(rule):
            print("udev      %s" % rule)
        else:
            # not fatal: many systems let the user open it anyway; only the open
            # failing needs this
            print("udev      rule not installed (add it if opening the device is denied)")

    try:
        found = transport.devices()
    except Exception as error:  # noqa: BLE001
        found = []
        print("device    cannot enumerate: %s" % error)
    if found:
        for device in found:
            # NOT `warm`: that is the module this file imports, and shadowing it here made
            # the cold branch below raise AttributeError on the one platform that had a
            # cold device in `found` at that moment (Linux hardware, 2026-11-18). A local
            # named after a module is a trap that only some test orders walk into.
            identity = "warm" if device.idProduct == 0x2480 else "cold"
            print("device    %04x:%04x (%s) bus %s addr %s"
                  % (device.idVendor, device.idProduct, identity, device.bus,
                     device.address))
    else:
        print("device    none on the bus")
        problems.append("plug the dongle in; Linux: lsusb | grep 3344; Windows: "
                        "check Device Manager and the WinUSB binding")

    if problems:
        print("")
        for problem in problems:
            print("  -> %s" % problem)
        return 1
    print("")
    cold = [d for d in found if d.idProduct == 0x1120]
    if cold:
        # Since 2026-11-18 the driver warms a cold stick itself, so this is only a problem
        # when the images are missing — the old text claimed the warm path *could not* run,
        # which stopped being true the day the P5b became automatic.
        try:
            warm.load_images()
            images = True
            why = None
        except warm.BringUpError as failure:
            images = False
            why = str(failure)
        if images:
            print("doctor    all layers present; the device is COLD (1120) and the")
            print("          driver will warm it on use: play, tune, scan and probe")
            print("          send the P5b themselves and print one line.")
        else:
            print("doctor    all layers present, but the device is COLD (1120) and")
            print("          the P5b images are not here: %s" % why)
            print("          Put them in firmware/ (they are not published) and the")
            print("          driver will warm the stick itself. See")
    else:
        print("doctor    all layers present; next: lme2510 tune --freq 479143")
    return 0


def cmd_selftest(_args):
    """Run the whole driver path against a simulated device, no hardware.

    This is what proves an install on a platform we have not run yet: the same
    Driver, the same init, tune, scan and stream start, with the bus answers the
    hardware device gave.
    """
    from lme2510 import sim

    transport = sim.SimulatedTransport()
    core = driver.Driver(transport)
    peak, levels = core.init()
    init_frames = len(transport.sent)
    word = core.tune(479143)
    tune_writes = len(transport.writes())
    locked, trace = core.scan()
    core.start_stream()
    started = [frame.hex() for frame in transport.sent[-2:]]

    print("selftest  init    %d frames, sweep peak 0x%02x" % (init_frames, peak))
    print("selftest  tune    %d writes in total, 0x76 = %s"
          % (tune_writes, "0x%02x" % word if word is not None else "-"))
    print("selftest  scan    %s (%d reads)" % ("LOCKED" if locked else "no lock",
                                              len(trace)))
    print("selftest  stream  %s" % " + ".join(started))
    checks = [
        (init_frames == 330, "init is 330 frames, got %d" % init_frames),
        (peak == 0x16, "sweep peak 0x16, got 0x%02x" % peak),
        (locked, "the scan locks"),
        (started == ["030600ff011f2081", "0600"], "the stream start frames"),
    ]
    for ok, what in checks:
        if not ok:
            print("selftest  FAIL    %s" % what)
            return 1
    print("selftest  OK")
    return 0


def cmd_tmcc(args):
    """Tune, read the demod's TMCC codeword, and print the channel's parameters.

    The demod decodes TMCC to demap the layers and hands the raw (184,102) block to the host at
    `0x4110`. What comes back is the truth about the multiplex, not about the tune: EWBS, partial
    reception, and each layer's modulation, code rate, interleave and segments. Mode and guard
    interval are **not** TMCC fields (they ride in the IIP), so they are deliberately absent.
    """
    device, _adapter, core = _open(args)
    try:
        _result, failure = _init(core)
        if failure:
            print("init      failed: %s" % failure, file=sys.stderr)
            return 2
        try:
            locked, _trace = tune_and_lock(core, args.freq)
        except ValueError as error:
            print("tune      refused: %s" % error, file=sys.stderr)
            return 2
        print("tune      %d kHz, %s" % (args.freq, "LOCKED" if locked else "no lock"))
        if not locked:
            print("tmcc      the demod only reports TMCC while it holds the lock",
                  file=sys.stderr)
            return 3
        try:
            decoded = tmcc.decode(tmcc.read_settled(core))
        except ValueError as error:
            print("tmcc      %s" % error, file=sys.stderr)
            return 1
        if not tmcc.valid(decoded):
            # IT9175's zero trap (2026-11-20): an undecoded register is not a multiplex, and this
            # block claims no segments at all - so do not print a mode-shaped line from it.
            print("tmcc      not decoded yet (the block claims no layer segments - the demod has not "
                  "decoded TMCC on this channel)", file=sys.stderr)
            return 1
        if getattr(args, "json", False):
            import json
            print(json.dumps(decoded, indent=1, sort_keys=True))
        else:
            print("tmcc      %s" % tmcc.describe(decoded))
    finally:
        close_quietly(device, "tmcc")
    return 0


def _wait_for_packets(seen, seconds, baseline=None):
    """Wait until the byte counter moves past ``baseline`` (or any bytes arrive); False on timeout."""
    start = seen["bytes"] if baseline is None else baseline
    deadline = time.monotonic() + max(0.05, seconds)
    while time.monotonic() < deadline:
        if seen["bytes"] > start:
            return True
        time.sleep(0.02)
    return False


def cmd_zap(args):
    """Change channel several times in **one** session, timing the two numbers apart.

    A channel change is not a bring-up (the sibling driver's account of the vendor's fast zap, 2026-11-20): its
    `PlayChannel` path runs no init, no upload and no demod reset, so `core.tune()` - 27 writes - is the
    whole cost on the wire. This command opens and inits **once**, then changes frequency for each channel
    and prints the two numbers the family must never merge:

        replay   time to send the change (what a vendor means by its zap number)
        lock     replay + the lock wait, i.e. the number a viewer feels

    The lock scan is the vendor's four-register state machine (`0x3025` bits in order, `0x3026`,
    `0x2023`, `0x50c5`), polled every 10 ms by design - a lock is necessary, not sufficient, so the plain
    mode does not shortcut it. `--stream` starts the pump before each change (the pipeline cost).

    `--live` is the **vendor's own shape**, transcribed from `mydigital+TV 5.15` (2026-11-20): the reader is
    started **once** and never stopped, a channel change is `tune` + re-arm the filter, and `setfrequency`'s
    return value is the lock verdict - the app never scans. This measures exactly that: one pipe, N changes,
    and per change the replay time, the re-arm time, how long until packets flowed again, and the tune word.
    `--compare` additionally runs the four-register scan so the two lock verdicts can be judged against each
    other; that comparison is the measurement the family asked for, not something to assume.
    """
    device, _adapter, core = _open(args)
    try:
        began = time.monotonic()
        core.init()
        if getattr(args, "live", False):
            until = threading.Event()
            seen = {"bytes": 0, "chunks": 0, "packets": 0, "at": time.monotonic()}

            def sink(chunk):
                seen["bytes"] += len(chunk)
                seen["chunks"] += 1
                seen["packets"] += len(chunk) // 188
                seen["at"] = time.monotonic()

            stream = reader.StreamReader(reader.transport_source(device), sink=sink)
            pump = threading.Thread(target=stream.run, kwargs={"until": until}, daemon=True,
                                    name="lme2510-zap-pump")
            core.start_stream()
            pump.start()
            if not _wait_for_packets(seen, getattr(args, "resume_seconds", 5.0)):
                print("zap         no packets after start; a change with no flow measures nothing",
                      file=sys.stderr)
                until.set()
                return 3
            survived = 0
            for frequency in args.freqs:
                before = seen["bytes"]
                began = time.monotonic()
                began = time.monotonic()
                word = core.tune(frequency)
                replay = (time.monotonic() - began) * 1000.0
                began = time.monotonic()
                core.start_stream()          # the vendor's filtersetting(0, "8191") + 06 00
                rearm = (time.monotonic() - began) * 1000.0
                began = time.monotonic()
                window = getattr(args, "verdict_seconds", 3.0)
                window = getattr(args, "verdict_seconds", 3.0)
                flowed = _wait_for_packets(seen, window, baseline=before)
                resumed = (time.monotonic() - began) * 1000.0
                verdict = ""
                # The family's rule, and the only shape these measurements support (2026-11-20): the stream
                # is the verdict. A scan costs 16-160 register reads and *stops this pump*, so it is paid only
                # once the stream has gone silent - where the pump is gone anyway. If the scan then says
                # locked, re-arm once and give the bytes a second window.
                if not flowed:
                    locked, trace = core.scan()
                    if locked:
                        core.start_stream()
                        began = time.monotonic()
                        flowed = _wait_for_packets(seen, window, baseline=before)
                        resumed = (time.monotonic() - began) * 1000.0
                        verdict = "  silent -> scan LOCKED (%d reads), re-armed -> %s" % (
                            len(trace), "flowing" if flowed else "still silent")
                    else:
                        verdict = ("  silent -> scan no lock (%d reads): the channel is silent - check the "
                                   "carrier before the driver" % len(trace))
                elif getattr(args, "compare", False):
                    locked, trace = core.scan()
                    verdict = "  scan %s (%d reads)  agree %s" % (
                        "LOCKED" if locked else "no lock", len(trace),
                        "yes" if (locked == bool(word)) else "NO")
                after = seen["bytes"]
                if flowed:
                    survived += 1
                print("zap %6d kHz  replay %5.0f ms  rearm %4.0f ms  resumed %5.0f ms  "
                      "word 0x%02x  packets %6d  word_locked=%s%s"
                      % (frequency, replay, rearm, resumed if flowed else float("nan"), word,
                         (after - before) // 188, bool(word), verdict))
            until.set()
            print("zap         %d/%d changes kept packets flowing (%.1f MiB read in total)"
                  % (survived, len(args.freqs), seen["bytes"] / (1024.0 * 1024.0)))
            return 0 if survived == len(args.freqs) else 3

        print("open+init   %6.0f ms (once per session)"
              % ((time.monotonic() - began) * 1000.0))
        for frequency in args.freqs:
            if getattr(args, "stream", False):
                core.start_stream()
            began = time.monotonic()
            core.tune(frequency)
            replay = (time.monotonic() - began) * 1000.0
            began = time.monotonic()
            locked, trace = core.scan()
            lock = (time.monotonic() - began) * 1000.0
            print("zap %6d kHz  replay %5.0f ms  lock %6.0f ms  total %6.0f ms  locked=%s (%d reads)"
                  % (frequency, replay, lock, replay + lock, locked, len(trace)))
    finally:
        close_quietly(device, "zap")
    return 0


def cmd_bml(args):
    """Tune, read for a while, and list the BML documents the data service carries."""
    from lme2510 import bml

    device, _adapter, core = _open(args)
    buffer = bytearray()
    try:
        _result, failure = _init(core)
        if failure:
            print("init      failed: %s" % failure, file=sys.stderr)
            return 2
        try:
            locked, _trace = tune_and_lock(core, args.freq)
        except ValueError as error:
            print("tune      refused: %s" % error, file=sys.stderr)
            return 2
        print("tune      %d kHz, %s" % (args.freq, "LOCKED" if locked else "no lock"))
        core.start_stream()
        stream = reader.StreamReader(reader.transport_source(device), sink=buffer.extend)
        total = stream.run(args.seconds)
    finally:
        close_quietly(device, "bml")

    data = bytes(buffer)
    found = bml.documents(data)
    print("bml       %d document(s) in %.1f MB" % (len(found), len(data) / 1e6))
    for index, document in enumerate(found, 1):
        print("  %d. %-24s %6d bytes  PID 0x%04x  seen %dx"
              % (index, document.title or "(untitled)", document.size,
                 document.pid, document.count))
        if args.save:
            import os
            os.makedirs(args.save, exist_ok=True)
            name = document.title or ("document-%d" % index)
            path = os.path.join(args.save, name if name.endswith(".bml") else name + ".bml")
            with open(path, "wb") as handle:
                handle.write(document.raw)
            print("     saved %s" % path)
    return 0 if found else 2


