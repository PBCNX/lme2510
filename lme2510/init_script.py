def frame_pairs(crystal=0x3E):
    """The (register, value) pairs with the crystal trim filled in."""
    out = []
    for register, value in SCRIPT:
        out.append((register, crystal if value is CRYSTAL_MARK else value))
    return out


def frames(crystal=0x3E, device=None):
    """The write frames of the script, in order, as they appear on the wire."""
    from lme2510 import replay
    return [replay.write_frame(PAGE | register, value, device=device)
            for register, value in frame_pairs(crystal)]
