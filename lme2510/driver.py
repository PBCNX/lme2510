"""The driver's core: a transport in, a tuned receiver and TS out. proved the flow on the hardware; this is the same flow as the library
the CLI (and later the JVM core) calls.  Nothing here knows about libusb: it takes
an object with ``exchange(frame) -> reply`` — send one frame, return the device's
answer — which is what `lme2510.transport` provides on every platform.

    core = Driver(transport)
    core.init()                       # our own warm init
    core.tune(479143)                 # our own set-frequency
    locked, trace = core.scan()       # the vendor's scan, transcribed
    core.start_stream()               # filter + 06 00
    # then read the bulk endpoint yourself: 4 x 51,200 B in flight

Every frame in that path is generated by this tree (the four literal blocks and
the bbm prefix are data with provenance, not a replay).
"""
import time

from lme2510 import init, lockcheck, replay, tune


class ByteReader:
    """The one-byte view `lockcheck.scan` wants over a register reader."""

    def __init__(self, read):
        self._read = read

    def read(self, register):
        data = self._read(register, 1)
        return data[0] if data else None


class DeviceTransport:
    """`exchange(frame) -> reply` over an `lme2510.transport.Device`.

    A write answers one byte (`0x88`); a read answers `0x55` plus the payload.  The
    pacing knob exists because the vendor's code waited a few milliseconds between
    writes and we do not yet know which of those waits matter.
    """

    def __init__(self, device, frame_delay=0.0):
        self.device = device
        self.frame_delay = frame_delay
        self.sent = 0

    def exchange(self, frame):
        self.device.write(frame)
        if self.frame_delay:
            time.sleep(self.frame_delay)
        want = 1 + frame[3] if frame[:1] == b"\x86" and len(frame) == 5 else 1
        reply = b""
        try:
            reply = self.device.read(want)
            # A reply can arrive split: the first transfer then ends on a short packet
            # (the marker alone) and the payload stays queued, which shifts every later
            # read. The LEAP showed exactly that ("34, 49, -1, -1"). Take the rest.
            while 0 < len(reply) < want:
                more = self.device.read(want - len(reply))
                if not more:
                    break
                reply += more
        except Exception:  # noqa: BLE001
            reply = reply or b""
        self.sent += 1
        return reply

    def send(self, frame):
        """Write one frame and **never read the answer**.

        On a wedged command endpoint the read is the failure: it blocks until the timeout, and on this
        chip a reset frame is answered by a device that is already resetting. IT9308's rule (2026-11-20):
        write the reboot, read nothing, close, reopen, and verify on the new handle. `exchange` stays
        for everything that needs an answer.
        """
        self.device.write(frame)
        self.sent += 1


class Driver:
    def __init__(self, transport, wait=None, poll_wait=None):
        self.transport = transport
        self.exchange = transport.exchange
        # `send` is the write-only path (a wedge recovery must not wait for a reply). It is None when the
        # transport cannot do it — deliberately not aliased to `exchange`, so a caller can tell the
        # difference instead of logging "sent without reading" over a call that did read.
        self.send = getattr(transport, "send", None)
        self.wait = wait or (lambda: None)
        # The lock poll runs on its own clock.  `wait` paces init and tune, where the
        # vendor's own waits are 1-2 ms; the scan needs the vendor's 10 ms between
        # reads (3 ms locked 0/10, 5 ms 1/10, 10 ms 10/10, measured 2026-11-19) and
        # using the caller's pacing made `scan` a coin flip in the CLI.
        self.poll_wait = poll_wait if poll_wait is not None else (
            lambda: time.sleep(lockcheck.WAIT))

    # -- reads ------------------------------------------------------------
    def read(self, register, count=1):
        """The payload of a register read (the bytes after `0x55`), or `b""`."""
        self.exchange(replay.select_frame(register))
        reply = self.exchange(replay.read_frame(register, count))
        if len(reply) >= 1 + count and reply[0] == 0x55:
            return reply[1:1 + count]
        return b""

    # -- the warm path ----------------------------------------------------
    def init(self, crystal=0x3E):
        """The warm init.  Returns the sweep's ``(peak, levels)``."""
        return init.run(self.exchange, crystal=crystal, wait=self.wait)

    def tune(self, freq_khz, peak=0x16):
        """Set the frequency.  Returns the `0x76` byte that decided the conditional."""
        return tune.run(self.exchange, self.read, freq_khz, peak=peak, wait=self.wait)

    def scan(self):
        """The vendor's lock scan, transcribed.  Returns ``(locked, trace)``."""
        return lockcheck.scan(ByteReader(self.read), wait=self.poll_wait)

    def start_stream(self, pids=(0x1FFF,), filtered=False):
        """Send the filter frame and `06 00`, in that order."""
        for frame in replay.stream_start_frames(list(pids), filtered=filtered):
            self.exchange(frame)

